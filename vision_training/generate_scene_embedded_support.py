from __future__ import annotations

import argparse
import json
import shutil
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SCENE_CLASSES = ("infant", "head_face", "blanket", "soft_object", "caregiver")
REFERENCE_DIR = (
    ROOT
    / "vendor"
    / "ruhmi-model-zoo"
    / "vision"
    / "object_detection"
    / "yolox_tiny"
    / "embedded_c"
)


@dataclass(frozen=True)
class SceneTensorContract:
    input_scale: float
    input_zero_point: int
    output_scale: float
    output_zero_point: int
    input_height: int = 224
    input_width: int = 224
    input_channels: int = 3
    num_anchors: int = 1029
    num_classes: int = len(SCENE_CLASSES)

    @property
    def output_channels(self) -> int:
        return 5 + self.num_classes


def c_float(value: float, precision: int = 17) -> str:
    literal = format(value, f".{precision}g")
    if "e" not in literal.lower() and "." not in literal:
        literal += ".0"
    return f"{literal}f"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "从五类 YOLOX-Tiny strict INT8 TFLite 生成 RA8P1 预处理、"
            "后处理、量化参数和类别标签"
        )
    )
    parser.add_argument("--model", required=True, type=Path)
    parser.add_argument(
        "--reference-dir",
        type=Path,
        default=REFERENCE_DIR,
        help="setup_external_repos.ps1 下载的 Renesas embedded_c 目录",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "artifacts" / "scene" / "embedded_support",
    )
    parser.add_argument("--score-threshold", type=float, default=0.25)
    parser.add_argument("--nms-threshold", type=float, default=0.45)
    parser.add_argument("--max-detections", type=int, default=100)
    parser.add_argument("--force", action="store_true")
    return parser.parse_args()


def render_model_metadata(
    contract: SceneTensorContract,
    *,
    score_threshold: float,
    nms_threshold: float,
    max_detections: int,
) -> str:
    return f"""/*
 * Generated by vision_training/generate_scene_embedded_support.py.
 * Tensor quantization values come from the trained TFLite model.
 */
#ifndef BABY_SCENE_MODEL_METADATA_H
#define BABY_SCENE_MODEL_METADATA_H

#include <stdint.h>

#define MODEL_NAME              "Baby YOLOX-Tiny 224 INT8"
#define MODEL_DATASET           "CribHD+SyRIP+self_capture"
#define MODEL_NUM_CLASSES       ({contract.num_classes}U)
#define MODEL_DTYPE             "int8"

#define MODEL_INPUT_H           ({contract.input_height})
#define MODEL_INPUT_W           ({contract.input_width})
#define MODEL_INPUT_C           ({contract.input_channels})
#define MODEL_INPUT_SIZE        (MODEL_INPUT_H * MODEL_INPUT_W * MODEL_INPUT_C)
#define INPUT_LETTERBOX_PAD     (114)
#define MODEL_INPUT_SCALE       ({c_float(contract.input_scale)})
#define MODEL_INPUT_ZERO_POINT  ({contract.input_zero_point})

#define MODEL_NUM_ANCHORS       ({contract.num_anchors}U)
#define MODEL_OUTPUT_CHANNELS   ({contract.output_channels}U)
#define MODEL_OUTPUT_SIZE       (MODEL_NUM_ANCHORS * MODEL_OUTPUT_CHANNELS)
#define MODEL_OUTPUT_SCALE      ({c_float(contract.output_scale)})
#define MODEL_OUTPUT_ZERO_POINT ({contract.output_zero_point})

#define MODEL_STRIDE_S8         (8U)
#define MODEL_STRIDE_S16        (16U)
#define MODEL_STRIDE_S32        (32U)
#define MODEL_GRID_S8           (28U)
#define MODEL_GRID_S16          (14U)
#define MODEL_GRID_S32          (7U)

#define POSTPROC_SCORE_THRESH   ({c_float(score_threshold, 9)})
#define POSTPROC_NMS_THRESH     ({c_float(nms_threshold, 9)})
#define POSTPROC_MAX_DETS       ({max_detections}U)
#define LOG_MAX_DETS            (20U)

#define NUM_TEST_IMAGES         (3U)
#define OUTPUT_IMAGE_MAX_SIZE   (921600U)

#endif /* BABY_SCENE_MODEL_METADATA_H */
"""


def render_labels_header(classes: tuple[str, ...] = SCENE_CLASSES) -> str:
    labels = ",\n".join(f'    "{label}"' for label in classes)
    return f"""/*
 * Deployment class order.  This order must match vision_models.yaml.
 */
#ifndef BABY_SCENE_LABELS_H
#define BABY_SCENE_LABELS_H

#define BABY_SCENE_CLASS_COUNT ({len(classes)}U)

static const char * const g_baby_scene_labels[BABY_SCENE_CLASS_COUNT] =
{{
{labels}
}};

#endif /* BABY_SCENE_LABELS_H */
"""


def inspect_model(model_path: Path) -> tuple[SceneTensorContract, dict]:
    try:
        import numpy as np
        import tensorflow as tf
    except ImportError as exc:
        raise SystemExit("缺少 TensorFlow；请先运行 setup.ps1") from exc

    interpreter = tf.lite.Interpreter(model_path=str(model_path))
    interpreter.allocate_tensors()
    inputs = interpreter.get_input_details()
    outputs = interpreter.get_output_details()
    if len(inputs) != 1 or len(outputs) != 1:
        raise SystemExit(f"场景模型必须单输入单输出，实际 {len(inputs)}/{len(outputs)}")

    input_detail = inputs[0]
    output_detail = outputs[0]
    input_shape = input_detail["shape"].tolist()
    output_shape = output_detail["shape"].tolist()
    failures: list[str] = []
    if input_shape != [1, 224, 224, 3]:
        failures.append(f"输入形状 {input_shape} != [1, 224, 224, 3]")
    if output_shape != [1, 1029, 10]:
        failures.append(f"输出形状 {output_shape} != [1, 1029, 10]")
    if input_detail["dtype"] != np.int8:
        failures.append(f"输入 dtype {input_detail['dtype']} 不是 int8")
    if output_detail["dtype"] != np.int8:
        failures.append(f"输出 dtype {output_detail['dtype']} 不是 int8")

    input_scale, input_zero = input_detail["quantization"]
    output_scale, output_zero = output_detail["quantization"]
    if abs(float(input_scale) - 1.0) > 1e-6 or int(input_zero) != -128:
        failures.append(
            "Renesas 参考预处理只支持 input scale=1.0、zero_point=-128；"
            f"当前为 {input_scale}/{input_zero}"
        )
    if float(output_scale) <= 0:
        failures.append(f"输出量化 scale 非正数: {output_scale}")
    if failures:
        raise SystemExit("; ".join(failures))

    contract = SceneTensorContract(
        input_scale=float(input_scale),
        input_zero_point=int(input_zero),
        output_scale=float(output_scale),
        output_zero_point=int(output_zero),
    )
    report = {
        "model": str(model_path.resolve()),
        "model_bytes": model_path.stat().st_size,
        "classes": list(SCENE_CLASSES),
        "input": {
            "shape": input_shape,
            "dtype": str(input_detail["dtype"]),
            "quantization": [contract.input_scale, contract.input_zero_point],
        },
        "output": {
            "shape": output_shape,
            "dtype": str(output_detail["dtype"]),
            "quantization": [contract.output_scale, contract.output_zero_point],
        },
        "source_buffer_contract": (
            "Renesas preprocessing.c receives RGB888 and swaps to the BGR order "
            "used by the official YOLOX/OpenCV pipeline"
        ),
    }
    return contract, report


def main() -> int:
    args = parse_args()
    if not args.model.is_file():
        raise SystemExit(f"找不到模型: {args.model}")
    required_reference_files = (
        "preprocessing.c",
        "preprocessing.h",
        "postprocessing.c",
        "postprocessing.h",
    )
    missing = [
        name for name in required_reference_files if not (args.reference_dir / name).is_file()
    ]
    if missing:
        raise SystemExit(
            f"Renesas embedded_c 不完整 ({', '.join(missing)})；"
            "请先运行 setup_external_repos.ps1"
        )
    if not 0 < args.score_threshold < 1:
        raise SystemExit("--score-threshold 必须在 0 和 1 之间")
    if not 0 < args.nms_threshold < 1:
        raise SystemExit("--nms-threshold 必须在 0 和 1 之间")
    if args.max_detections <= 0:
        raise SystemExit("--max-detections 必须大于 0")

    contract, report = inspect_model(args.model)
    if args.output.exists() and any(args.output.iterdir()):
        if not args.force:
            raise SystemExit(f"输出目录非空；确认后加 --force: {args.output}")
        shutil.rmtree(args.output)

    common_dir = args.output / "common"
    source_dir = args.output / "src"
    common_dir.mkdir(parents=True)
    source_dir.mkdir(parents=True)
    (common_dir / "model_metadata.h").write_text(
        render_model_metadata(
            contract,
            score_threshold=args.score_threshold,
            nms_threshold=args.nms_threshold,
            max_detections=args.max_detections,
        ),
        encoding="utf-8",
    )
    (common_dir / "baby_scene_labels.h").write_text(
        render_labels_header(),
        encoding="utf-8",
    )
    for name in required_reference_files:
        shutil.copy2(args.reference_dir / name, source_dir / name)

    report.update(
        {
            "reference_dir": str(args.reference_dir.resolve()),
            "score_threshold": args.score_threshold,
            "nms_threshold": args.nms_threshold,
            "max_detections": args.max_detections,
            "copied_reference_files": list(required_reference_files),
            "important": (
                "Do not copy the official COCO model_metadata.h: it is 80-class "
                "and its output quantization does not match this custom model."
            ),
        }
    )
    (args.output / "embedded_support.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (args.output / "README.txt").write_text(
        "Add common/ and src/ to the RA8P1 vision build together with the "
        "RUHMI-generated model files. preprocessing.c expects an RGB888 source "
        "buffer and converts it to the BGR tensor order used during YOLOX "
        "training. Verify one-image parity before enabling safety fusion.\n",
        encoding="utf-8",
    )
    print(f"嵌入式支持文件已生成: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
